-- 프로필 사진 — authors.avatar_url.
--
--  앱 팀 요청(2026-08-31). 설정 화면의 프로필 편집을 붙이려는데 저장할 곳이 없었다.
--  닉네임은 컬럼이 있었지만 **바꾸는 API 가 없어서**, 글·후기·플랜 저장의 authorNm
--  부수효과로만 바뀌었다(글을 쓰지 않으면 이름을 바꿀 방법이 없었다).
--
--  ⚠️ URL 만 담는다. 파일은 기존 업로드 라우트(POST /v1/reviews/images)가 저장하고,
--     그 라우트는 파일명을 내용의 sha256 으로 정해 경로 접두사가 뜻을 갖지 않는다 —
--     그래서 후기·게시글·프로필이 한 저장소를 공유해도 무방하다(별도 업로드 경로를
--     만들면 리사이즈·검증 규칙이 두 벌이 된다).
--
--  ⚠️ 값 검증을 DB 제약으로 걸지 않는다. 스킴·길이 검사는 라우트가 하고, 나중에 CDN 을
--     붙여 호스트가 바뀔 때 마이그레이션 없이 따라가야 한다.
--
--  migrate 는 내용 해시로 재적용을 판단하므로 이 파일은 멱등이어야 한다.

alter table authors add column if not exists avatar_url text;
