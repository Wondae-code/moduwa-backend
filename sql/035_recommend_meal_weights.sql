-- 식사 시간대 가중치 — 아침 자리에 횟집이, 저녁 자리에 죽집이 오는 것을 막는다.
--
--  관광공사 유형(39=음식점)에는 시간대 정보가 없어서, 카카오 세부 분류
--  ('음식점 > 한식 > 해장국')로 가른다. 무장애 음식점 중 카카오 매칭이 되는 곳에만 적용된다.
--
--  ⚠️ **거르지 않고 점수만 민다.** 후보가 적은 지역(가평 28곳)에서 거르면 칸이 통째로 비는데,
--     어울리지 않는 식당이라도 있는 편이 빈 칸보다 낫다.
--
--  do nothing 이다 — 운영에서 조정한 값을 배포가 되돌리면 안 된다(033 과 같은 규칙).
insert into recommend_weights (key, value, note) values
  ('meal.time_match',     20, '아침에 해장국·죽·베이커리 / 저녁에 고기·해물처럼 시간대가 맞을 때'),
  ('meal.time_mismatch', -25, '아침에 횟집처럼 시간대가 어긋날 때. 거르지는 않는다')
on conflict (key) do nothing;

-- 식사 자리에 백화점·몰이 들어가는 것을 막는다.
--  서울처럼 쇼핑시설이 인기순위 상위에 몰린 지역에서는 세 끼가 전부 백화점이 됐다
--  (더현대 서울 · 아이파크몰 · 롯데백화점). 전통시장은 실제 식사 목적지라 예외로 둔다.
--  ⚠️ 쇼핑 유형 자체를 막지는 않는다 — 가평은 음식점이 3곳뿐이라 막으면 칸이 통째로 빈다.
insert into recommend_weights (key, value, note) values
  ('meal.non_restaurant', -35, '식사 자리의 백화점·몰(시장은 제외). 막지 않고 점수로 민다')
