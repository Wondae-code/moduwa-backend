-- 이동 수단(자차·뚜벅이·휠체어)을 추천에 반영하는 가중치.
--
--  앱은 1/6 에서 이동 수단을 묻고 plans.party.mobilities 에 저장해 왔지만, 추천 요청에는
--  싣지 않아 서버가 알 수 없었다. 같은 39km 코스가 자차에게는 40분이고 뚜벅이에게는
--  못 가는 거리인데 둘에게 같은 코스를 내고 있었다.
--
-- ⚠️ **거리는 배수가 핵심이고 상한이 아니다.** 상한만 30→100 으로 올렸을 때는 가평 동선이
--    39→36km 로 거의 그대로였는데, 배수를 1.5→4 로 올리니 39→14km 로 잡혔다(2026-09-20 실측).
--    앞서 "감점이 아니라 숙소 선택이 원인" 이라고 본 것은 상한만 만져 본 탓이었다.
--
--  실측 (가평·양평 2박, 숙소↔일정 최원거리 / 구간 최대):
--    배수 1.5 상한 30 (자차, 지금)   39km / 46km
--    배수 4   상한 80 (뚜벅이·휠체어) 14km /  8km
--    배수 8   상한 150               14km / 10km   ← 4 에서 이미 잡힌다, 더 올릴 이유가 없다
--
-- ⚠️ 자차 값(1.5/30)은 **지금 동작 그대로**다. 코드에 박혀 있던 것을 설정으로 옮기기만 한다 —
--    033 의 "점수는 코드에 없다" 규칙이고, 값을 바꿀 때 배포를 기다리지 않게 한다.
--
--  wheelchair_fit: 휠체어 축 12개 속성 중 채워진 개수(실측 0~10, 중앙값 3)당 점수.
--    access_wheelchair 플래그는 89% 가 true 라 가려내지 못해서 개수를 쓴다.
--    4점이면 0개(912곳)와 6개(805곳)가 24점 차 — hub_bonus 최대(30)와 비슷한 무게다.
--  transit_bonus: 대중교통 안내가 있는 곳(유형별 43~88%). 뚜벅이에게만, 자차가 없을 때만.
--
--  on conflict do nothing — 운영에서 조정한 값을 배포가 되돌리면 안 된다(033 과 같은 규칙).
insert into recommend_weights (key, value, note) values
  ('mobility.distance_mult',      1.5, '자차·미지정: 직전 장소와의 거리 1km 당 감점'),
  ('mobility.distance_cap',        30, '자차·미지정: 거리 감점 상한'),
  ('mobility.foot_distance_mult',   4, '뚜벅이·휠체어: 1km 당 감점. 배수가 동선을 좁히는 핵심이다'),
  ('mobility.foot_distance_cap',   80, '뚜벅이·휠체어: 거리 감점 상한'),
  ('mobility.wheelchair_fit',       4, '휠체어: 무장애 속성 1개당 가점(0~10개)'),
  ('mobility.transit_bonus',       12, '뚜벅이: 대중교통 안내가 있는 곳')
on conflict (key) do nothing;

-- 휠체어 이용자에게는 "접근성을 모르는 곳" 이 더 큰 문제다. 동선을 좁히면 닿는 범위의
--  조사된 식당이 줄어 미조사가 그 자리를 메운다 — 가평 실측 4/24 → 10/24.
--  그래서 기본(-18)보다 세게 민다. 막지는 않는다: 가평은 조사된 식당이 1곳뿐이라(039)
--  걸러 내면 아홉 끼가 통째로 빈다. 모르는 곳을 섞는 것보다 빈 코스가 더 나쁘다.
insert into recommend_weights (key, value, note) values
  ('mobility.wheelchair_unsurveyed', -40, '휠체어: 무장애 조사를 받지 않은 곳(기본 -18 보다 세게)')
on conflict (key) do nothing;

-- ── 가평처럼 데이터가 얇은 곳에서는 거리와 접근성을 **동시에** 만족할 수 없다
--
--  가평·양평에서 휠체어를 고르면 동선이 39km 다(뚜벅이는 14km). 조사된 무장애 장소가 두 군에
--  걸쳐 흩어져 있어서다. 거리 상한을 80→250 으로 올려 봐도 39→36km 로 거의 안 잡히고,
--  대신 미조사가 3→6곳으로 늘어 더 나빠진다(2026-09-20 실측). 배수를 더 올리면 동선은
--  좁아지지만 미조사가 24곳 중 10곳이 된다.
--
--  둘 중 **접근성을 택했다.** 039 주석이 이미 정한 원칙 그대로다 — "접근성을 모르는 곳을
--  코스 전반에 섞으면 무장애 앱의 약속이 무너진다". 휠체어 이용자를 조사되지 않은 식당으로
--  보내는 것이 이 앱이 막으려는 바로 그 일이고, 먼 것은 화면에 보이지만 못 들어가는 것은
--  가서야 안다. 응답의 notes 에 includes_unsurveyed 가 실리므로 앱이 안내할 수 있다.
--
--  뒤집으려면 mobility.foot_distance_mult 를 올리면 된다(4 → 8 이면 동선이 좁아지고
--  미조사가 늘어난다). 기획 판단이 서면 값 한 줄로 바꿀 수 있게 설정에 뒀다.
